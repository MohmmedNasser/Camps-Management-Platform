/**
 * Builds assets/vendor/supabase-js.js: @supabase/supabase-js as ONE
 * self-contained browser ES module, served from our own origin.
 *
 * Importing it from esm.sh instead cost a dependency tree of ~15 modules on a
 * third-party host (auth-js, realtime-js, … plus node polyfills such as
 * buffer/process/events/tty), each discovered only after its parent arrived —
 * the longest chain on the login page under mobile throttling, and short
 * cache lifetimes we cannot control.
 *
 * The bundled version is whatever supabase/package.json pins (installed in
 * supabase/node_modules), so the browser and the test suites run the same
 * library. Re-run after bumping it, and commit the output:
 *
 *   cd supabase && npm install && npm run vendor:supabase-js
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const ESBUILD = 'esbuild@0.24.2';
const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
const MODULES = resolve(ROOT, 'supabase/node_modules');
const TARGET = resolve(ROOT, 'assets/vendor/supabase-js.js');

const { version } = JSON.parse(readFileSync(join(MODULES, '@supabase/supabase-js/package.json'), 'utf8'));

const work = mkdtempSync(join(tmpdir(), 'vendor-supabase-'));
try {
  const entry = join(work, 'entry.mjs');
  const out = join(work, 'out.mjs');
  writeFileSync(entry, "export { createClient } from '@supabase/supabase-js';\n");

  execFileSync(
    'npx',
    [
      '--yes', ESBUILD, entry,
      '--bundle', '--format=esm', '--platform=browser', '--target=es2022',
      '--minify', '--legal-comments=none', `--outfile=${out}`,
    ],
    { stdio: 'inherit', shell: process.platform === 'win32', env: { ...process.env, NODE_PATH: MODULES } }
  );

  const code = readFileSync(out, 'utf8');
  // A leftover import would mean a module esbuild could not inline — the
  // browser would then request it from a path that does not exist.
  if (/^import\s|[;}]import\s*["{*\w]/.test(code)) fail('bundle still contains a static import');

  writeFileSync(
    TARGET,
    `/*! @supabase/supabase-js ${version} — MIT License, Copyright (c) 2020 Supabase.
 * GENERATED by supabase/scripts/vendor-supabase-js.mjs (${ESBUILD}) — do not edit. */
${code}`,
    'utf8'
  );
  process.stdout.write(`  wrote ${TARGET} (supabase-js ${version}, ${Buffer.byteLength(code)} bytes)\n`);
} finally {
  rmSync(work, { recursive: true, force: true });
}

function fail(message) {
  process.stderr.write(`\n  ✖ vendor-supabase-js: ${message}\n\n`);
  process.exit(1);
}
