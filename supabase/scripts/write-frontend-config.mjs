/**
 * Generates assets/js/core/supabase-config.js from .env.
 *
 * The frontend has no build step, so the two browser-safe values have to be
 * written to disk as an ES module. This script exists mainly to make one
 * mistake impossible: it refuses to write anything that looks like a secret /
 * service_role key into a file served to browsers.
 *
 *   cd supabase && npm run frontend:config
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
const TARGET = resolve(ROOT, 'assets/js/core/supabase-config.js');

const env = parseEnv(resolve(ROOT, '.env'));

const url = env.SUPABASE_URL;
const key = env.SUPABASE_ANON_KEY || env.SUPABASE_PUBLISHABLE_KEY;

if (!url || !key) {
  fail('SUPABASE_URL and SUPABASE_ANON_KEY must both be set in .env');
}

// A secret key in a browser file bypasses every RLS policy in the project.
// Refuse rather than warn.
if (/^sb_secret_/.test(key) || key === env.SUPABASE_SECRET_KEY || key === env.SUPABASE_SERVICE_ROLE_KEY) {
  fail(
    'SUPABASE_ANON_KEY holds a SECRET key. That key bypasses Row Level Security ' +
      'and must never be served to a browser. Use the publishable key.'
  );
}

writeFileSync(
  TARGET,
  `/**
 * GENERATED by supabase/scripts/write-frontend-config.mjs — do not edit.
 * Regenerate with: cd supabase && npm run frontend:config
 *
 * Contains the PUBLISHABLE key only. It is safe in a browser: Row Level
 * Security decides what the signed-in user may read or write.
 */

export const SUPABASE_URL = ${JSON.stringify(url)};

export const SUPABASE_ANON_KEY = ${JSON.stringify(key)};
`,
  'utf8'
);

process.stdout.write(`  wrote ${TARGET}\n  project: ${url}\n`);

function parseEnv(path) {
  const result = {};
  let contents;
  try {
    contents = readFileSync(path, 'utf8');
  } catch {
    fail(`No .env found at ${path}. Copy .env.example to .env first.`);
  }
  for (const line of contents.split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (match) result[match[1]] = match[2].trim().replace(/^["']|["']$/g, '');
  }
  return result;
}

function fail(message) {
  process.stderr.write(`\n  ✖ ${message}\n\n`);
  process.exit(1);
}
